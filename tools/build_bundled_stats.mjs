/**
 * build_bundled_stats.mjs - regenerate src/officialMatchStats.js from the compact
 * stats the app already loads at runtime.
 *
 * The bundled module is the offline fallback: app.js and recommender.js import it
 * statically, and `updateOfficialStats` overwrites it once the remote compact JSON
 * arrives. It was last generated 2026-06-21 off 365,519 teams and contains no
 * Lucia at all, so a desktop user with no network scored the current roster on
 * three-month-old data. It was also 110MB - parsed on every single launch,
 * online or off - because it carried the full uncompacted tables.
 *
 * Emitting it from src/officialMatchStats.compact.json fixes both: the data is
 * current, and it is the exact shape the app runs on in the normal online path,
 * so the offline path stops being a different model.
 *
 * Usage:
 *   node tools/build_bundled_stats.mjs
 *   node tools/build_bundled_stats.mjs --in src/officialMatchStats.compact.json
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function parseArgs() {
  const args = {
    in: path.join(ROOT, "src", "officialMatchStats.compact.json"),
    out: path.join(ROOT, "src", "officialMatchStats.js"),
  };
  for (let i = 2; i < process.argv.length; i += 1) {
    const key = process.argv[i];
    if (!key.startsWith("--")) continue;
    const value = process.argv[i + 1];
    i += 1;
    if (key === "--in") args.in = path.resolve(ROOT, value);
    else if (key === "--out") args.out = path.resolve(ROOT, value);
  }
  return args;
}

// Every named export app.js and recommender.js take from this module.
const TABLES = [
  "officialCandidateStatsByTier",
  "officialCombatStatsByTier",
  "officialCompositionStatsByTier",
  "officialEmpiricalVectorStatsByTier",
  "officialPairStatsByTier",
  "officialTraitBuildStatsByTier",
  "officialTraitStatsByTier",
];

async function main() {
  const args = parseArgs();
  const rel = (p) => path.relative(ROOT, p).replace(/\\/g, "/");
  const compact = JSON.parse(await fs.readFile(args.in, "utf8"));

  const missing = TABLES.filter((name) => !compact[name]);
  if (missing.length) throw new Error(`compact stats are missing: ${missing.join(", ")}`);

  const lines = [
    "// Generated by tools/build_bundled_stats.mjs. Do not edit by hand.",
    `// Offline fallback, from ${rel(args.in)}.`,
    "// Overwritten at runtime by updateOfficialStats() once the remote compact",
    "// stats load; this is what the app scores on when that fetch fails.",
    `// source generatedAt: ${compact.source?.generatedAt ?? "unknown"}`,
    `// validTeams: ${compact.source?.validTeams ?? "unknown"}`,
    "",
    `export const OFFICIAL_MATCH_SOURCE = ${JSON.stringify(compact.source ?? {}, null, 2)};`,
    "",
    `export const BAYESIAN_ALPHA = ${JSON.stringify(compact.alpha ?? 80)};`,
    "",
    `export const OFFICIAL_V2_WEIGHTS = ${JSON.stringify(compact.weights ?? {}, null, 2)};`,
    "",
  ];
  // Emitted as JSON.parse of a string literal rather than as object literals.
  // V8 parses JSON several times faster than the equivalent JavaScript source, and
  // this module is imported statically by app.js and recommender.js, so its parse
  // cost is paid on every single launch before anything renders. Measured on the
  // 2026-09-05 build: 894ms as object literals, ~230ms this way.
  const payload = {};
  for (const name of TABLES) payload[name] = compact[name];
  lines.push(
    "// eslint-disable-next-line",
    `const DATA = JSON.parse(${JSON.stringify(JSON.stringify(payload))});`,
    "",
  );
  for (const name of TABLES) {
    lines.push(`export const ${name} = DATA.${name};`);
  }
  lines.push("");
  lines.push(
    "// Tier buckets collapse to the ones the tables actually carry rows for.",
    "export function officialStatsBucketForTier(tier = \"all\") {",
    "  const bucketMap = {",
    "    all: \"all\",",
    "    iron_gold: \"iron_gold\",",
    "    platinum_diamond: \"platinum_diamond\",",
    "    meteor_mithril: \"meteor_mithril\",",
    "    demigod_eternity: \"demigod_eternity\",",
    "    iron_bronze: \"iron_gold\",",
    "    silver_gold: \"iron_gold\",",
    "    diamond: \"platinum_diamond\",",
    "    mithril_plus: \"meteor_mithril\",",
    "  };",
    "  const preferred = bucketMap[tier] ?? tier ?? \"all\";",
    "  if (officialCandidateStatsByTier[preferred] || officialCompositionStatsByTier[preferred] "
      + "|| officialTraitBuildStatsByTier[preferred]) return preferred;",
    "  return \"all\";",
    "}",
    "",
  );

  const text = lines.join("\n");
  await fs.writeFile(args.out, text, "utf8");
  const before = await fs.stat(args.in);
  console.log(`wrote ${rel(args.out)} (${(text.length / 1e6).toFixed(1)}MB from a ${(before.size / 1e6).toFixed(1)}MB compact)`);
  console.log(`  teams: ${compact.source?.validTeams ?? "?"} | generatedAt: ${compact.source?.generatedAt ?? "?"}`);
}

main().catch((error) => { console.error(error); process.exit(1); });
