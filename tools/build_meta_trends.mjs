import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import readline from 'node:readline';
import { createGunzip } from 'node:zlib';
import { characterVariants } from '../src/data.js';
import { FALLBACK_CHARACTER_CODE_TO_ID } from './character_code_map.mjs';
import { createTrendAccumulator } from './lib/meta_trends.mjs';

const args=process.argv.slice(2);
const option=(name,fallback)=>{const i=args.indexOf(name);return i<0?fallback:args[i+1];};
const input=option('--in','data/ml-training/corpus.jsonl');
const output=option('--out','src/metaTrends.json');
const stat=await fsp.stat(input);
const files=stat.isDirectory()?(await fsp.readdir(input)).filter(n=>n.endsWith('.jsonl.gz')||n.endsWith('.jsonl')).sort().map(n=>path.join(input,n)):[input];
async function* records() {
  for (const file of files) {
    const stream=fs.createReadStream(file);
    const lines=readline.createInterface({input:file.endsWith('.gz')?stream.pipe(createGunzip()):stream,crlfDelay:Infinity});
    for await (const line of lines) {if (line.trim()) yield JSON.parse(line);}
  }
}
const variants=new Map();
for (const c of characterVariants) {if(!variants.has(c.characterId))variants.set(c.characterId,[]);variants.get(c.characterId).push(c);}
const counts=new Map();let season=0;
for await (const row of records()) {
  if(Number(row.matchingMode)!==3)continue;
  season=Math.max(season,Number(row.seasonId)||0);
  for (const player of row.players??[]) {
    const choices=variants.get(FALLBACK_CHARACTER_CODE_TO_ID[player.character]);
    if(choices?.length!==1||player.weapon===undefined)continue;
    const key=String(player.weapon), value=choices[0].weapon;
    if(!counts.has(key))counts.set(key,new Map());
    const counter=counts.get(key);counter.set(value,(counter.get(value)??0)+1);
  }
}
const weapons=new Map([...counts].map(([key,values])=>[key,[...values].sort((a,b)=>b[1]-a[1])[0][0]]));
const validIds=new Set(characterVariants.map(c=>c.variantId));
const tracker=createTrendAccumulator({asOf:option('--as-of',new Date().toISOString())});
let scanned=0,accepted=0;
for await (const row of records()) {
  scanned++;
  if(Number(row.matchingMode)!==3||Number(row.seasonId)!==season)continue;
  const members=row.members?.map(m=>m.variantId)??(row.players??[]).map(player=>{
    const id=FALLBACK_CHARACTER_CODE_TO_ID[player.character], choices=variants.get(id);
    if(choices?.length===1)return choices[0].variantId;
    const weapon=id==='sho'?({15:'dagger',19:'spear'}[player.weapon]??weapons.get(String(player.weapon))):weapons.get(String(player.weapon));
    return choices?.find(c=>c.weapon===weapon)?.variantId;
  });
  if(!members.every(id=>validIds.has(id)))continue;
  if(tracker.add({gameId:row.gameId,teamKey:row.teamKey,startedAt:row.startedAt,tierBucket:row.tierBucket,
    placement:Number(row.rank??row.result?.placement),members}))accepted++;
}
const result={...tracker.finish(),season,scannedTeams:scanned,acceptedTeams:accepted};
await fsp.mkdir(path.dirname(output),{recursive:true});
await fsp.writeFile(output,JSON.stringify(result,null,2)+'\n');
await fsp.writeFile(output.replace(/\.json$/,'.js'),'// Generated by tools/build_meta_trends.mjs.\nexport const metaTrends = '+JSON.stringify(result)+';\n');
console.log(JSON.stringify({output,season,scanned,accepted,windows:[result.previousStart,result.recentStart,result.end],
  byTier:Object.fromEntries(Object.entries(result.byTier).map(([k,v])=>[k,{previous:v.previousTeams,recent:v.recentTeams,rising:v.rows.length}]))}));
